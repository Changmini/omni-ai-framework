#!/usr/bin/env bash
# One-time setup for Omni Agent Terminal on Linux, including WSL (WSLg).
#
#   scripts/setup-linux.sh            install everything (asks for sudo)
#   scripts/setup-linux.sh --dry-run  only print what it would do
#
# 1. apt packages: build tools for node-pty, Electron's runtime libraries
#    (package names picked per Ubuntu/Debian release), a symbol font
# 2. npm install (node-pty builds itself here, once build tools exist)
# 3. Electron's chrome-sandbox permissions (needs root once)
# 4. a launcher (~/.local/bin/omni-agent-terminal) and a menu entry
#
# Korean text needs no system font: the app bundles Nanum Gothic Coding.
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DRY_RUN=0
[ "${1:-}" = "--dry-run" ] && DRY_RUN=1

say()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }
run()  { printf '    $ %s\n' "$*"; [ "$DRY_RUN" = 1 ] || "$@"; }

# ---------- 0. checks ----------
[ "$(uname -s)" = "Linux" ] || die "Linux(또는 WSL)에서 실행하세요. Windows는 npm install만 하면 됩니다."
if [ "$(id -u)" = 0 ] && [ -n "${SUDO_USER:-}" ]; then
  die "sudo 없이 실행하세요. 필요한 단계에서만 스크립트가 sudo를 요청합니다."
fi
SUDO=""
[ "$(id -u)" = 0 ] || SUDO="sudo"

command -v node >/dev/null 2>&1 || die "Node.js 20 이상이 필요합니다 (https://nodejs.org 또는 nvm)."
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
[ "$NODE_MAJOR" -ge 20 ] || die "Node.js 20 이상이 필요합니다 (현재 $(node -v))."
command -v npm >/dev/null 2>&1 || die "npm이 없습니다."

IS_WSL=0
grep -qi microsoft /proc/version 2>/dev/null && IS_WSL=1
if [ "$IS_WSL" = 1 ]; then
  if [ -d /mnt/wslg ] || [ -n "${WAYLAND_DISPLAY:-}${DISPLAY:-}" ]; then
    say "WSL + WSLg 감지: 앱 창이 Windows 바탕화면에 뜹니다."
  else
    warn "WSLg(리눅스 GUI)가 보이지 않습니다. Windows 11 또는 최신 WSL(wsl --update)이 필요합니다."
  fi
fi

# ---------- 1. apt packages ----------
if command -v apt-get >/dev/null 2>&1; then
  say "패키지 목록 갱신"
  run $SUDO apt-get update -qq

  # First name that this release knows (Ubuntu 24.04 renamed several to *t64).
  pick() {
    local name
    for name in "$@"; do
      if apt-cache show "$name" >/dev/null 2>&1; then echo "$name"; return 0; fi
    done
    return 1
  }
  PKGS=(build-essential python3 git curl xdg-utils fonts-dejavu-core)
  for alts in \
    "libgtk-3-0t64 libgtk-3-0" \
    "libasound2t64 libasound2" \
    "libatspi2.0-0t64 libatspi2.0-0" \
    "libnss3" "libgbm1" "libxss1" "libxtst6" "libnotify4" "libsecret-1-0" "libxkbcommon0"; do
    # shellcheck disable=SC2086
    if p="$(pick $alts)"; then PKGS+=("$p"); else warn "패키지를 찾지 못함: $alts (건너뜀)"; fi
  done
  say "필요한 패키지 설치: ${PKGS[*]}"
  run $SUDO apt-get install -y -qq "${PKGS[@]}"
else
  warn "apt-get이 없습니다. 아래에 해당하는 패키지를 직접 설치하세요:"
  warn "  C/C++ 빌드 도구, python3, curl, GTK3, NSS, ALSA, libgbm, libxss, libxtst, libnotify, libsecret"
fi

# ---------- 2. npm install ----------
cd "$APP_DIR"
say "npm install (node-pty는 여기서 리눅스용으로 빌드됩니다)"
run npm install --no-fund --no-audit

if [ "$DRY_RUN" = 0 ] && ! node -e "require('node-pty')" >/dev/null 2>&1; then
  say "node-pty 다시 빌드"
  (cd node_modules/node-pty && run npx --yes node-gyp rebuild)
  node -e "require('node-pty')" >/dev/null 2>&1 || die "node-pty를 빌드하지 못했습니다. 위 오류를 확인하세요."
fi

# ---------- 3. chrome-sandbox ----------
SANDBOX="$APP_DIR/node_modules/electron/dist/chrome-sandbox"
if [ -f "$SANDBOX" ] || [ "$DRY_RUN" = 1 ]; then
  say "Electron 샌드박스 권한 설정 (root 소유 + setuid)"
  if ! { run $SUDO chown root:root "$SANDBOX" && run $SUDO chmod 4755 "$SANDBOX"; }; then
    warn "권한을 설정하지 못했습니다. 실행기가 --no-sandbox로 대신 실행합니다."
  fi
else
  warn "Electron이 설치되지 않았습니다($SANDBOX 없음). npm install 출력을 확인하세요."
fi

# ---------- 4. launcher + menu entry ----------
BIN_DIR="$HOME/.local/bin"
LAUNCHER="$BIN_DIR/omni-agent-terminal"
DESKTOP_DIR="$HOME/.local/share/applications"
DESKTOP="$DESKTOP_DIR/omni-agent-terminal.desktop"
say "실행기 만들기: $LAUNCHER"
if [ "$DRY_RUN" = 0 ]; then
  mkdir -p "$BIN_DIR" "$DESKTOP_DIR"
  cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Generated by scripts/setup-linux.sh. Starts Omni Agent Terminal detached
# from the calling terminal, so closing that terminal leaves the app open.
APP_DIR="$APP_DIR"
ELECTRON="\$APP_DIR/node_modules/electron/dist/electron"
SANDBOX="\$APP_DIR/node_modules/electron/dist/chrome-sandbox"
FLAGS=()
# Without a root-owned setuid chrome-sandbox Electron will not start sandboxed.
if [ ! -u "\$SANDBOX" ] || [ "\$(stat -c %u "\$SANDBOX" 2>/dev/null)" != 0 ]; then
  FLAGS+=(--no-sandbox)
fi
[ -x "\$ELECTRON" ] || { echo "Electron이 없습니다. \$APP_DIR/scripts/setup-linux.sh 를 다시 실행하세요." >&2; exit 1; }
cd "\$HOME"
exec setsid -f "\$ELECTRON" "\$APP_DIR" "\${FLAGS[@]}" "\$@" >/dev/null 2>&1
EOF
  chmod +x "$LAUNCHER"
  cat > "$DESKTOP" <<EOF
[Desktop Entry]
Type=Application
Name=Omni Agent Terminal
Comment=Terminal for running and watching Claude Code sessions
Exec="$LAUNCHER"
Icon=utilities-terminal
Terminal=false
Categories=Development;System;TerminalEmulator;
EOF
fi

say "완료"
echo "    실행: omni-agent-terminal"
case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) echo "    ($BIN_DIR 이 PATH에 없으면 새 터미널을 열거나 $LAUNCHER 로 실행하세요)" ;;
esac
if [ "$IS_WSL" = 1 ]; then
  echo "    WSLg에서는 Windows 시작 메뉴에도 'Omni Agent Terminal'로 나타날 수 있습니다."
fi
